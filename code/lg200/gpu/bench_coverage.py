#!/usr/bin/env python3
"""CS bench coverage manifest: what is measured, what is not, and why.

Joins three sources that already exist and are regenerated by the normal
workflow:

  build/cs_bench_results.tsv        run_bench.py (per-mnemonic OK/SKIP)
  build/gpu_cs_generic_results.tsv  run_gpu.py --pipe cs (correctness status)

and adds the family + reason for every row the bench cannot measure.  The point
is that "497 of 768" is auditable rather than a claim: a row that PASSES
correctness but has no bench row is a per-family template gap, while a row that
is SKIP-ENVELOPE on correctness too is a carrier limitation.

    python3 bench_coverage.py [--out build/cs_bench_coverage.tsv]
"""
import csv
import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BENCH = ROOT / "build" / "cs_bench_results.tsv"
CORR = ROOT / "build" / "gpu_cs_generic_results.tsv"
OUT = ROOT / "build" / "cs_bench_coverage.tsv"

# family -> (prefixes, why the bench has no template for it)
FAMILIES = [
    (("atomic_sm", "load_sm", "store_sm", "copy_sm"),
     "shared memory (LDS)", "needs an LDS window"),
    (("atomic_v_flat", "load_v_flat", "store_v_flat", "load_s_flat",
      "store_s_flat"), "flat memory", "needs a flat address operand"),
    (("atomic_v_buff", "load_v_buff", "store_v_buff", "load_s_buff",
      "store_s_buff"), "buffer memory", "needs a hydrated buffer descriptor"),
    (("atomic_v_tex", "load_v_tex", "store_v_tex"), "texture memory",
     "needs a texture descriptor"),
    (("samp", "gather"), "sampler / gather",
     "needs a texture + sampler descriptor"),
    (("sio",), "SIO", "outside the codec's variants"),
    (("v_movindex",), "refused by name", "its register window wedged CPIPE"),
]
CONTROL = ("nop", "exit", "check", "barrier", "trap", "rfe", "b", "jirl",
           "jpop", "jpush", "cb", "czb", "flag", "getpc", "getreg", "getlod",
           "getresinfo", "v_emit2", "v_emit3", "prefix_sw", "prefix_tp4",
           "prefix_tp8")


def classify(m):
    for prefixes, fam, why in FAMILIES:
        if m.startswith(prefixes):
            return fam, why
    if m in CONTROL:
        return "control / flow / system", "no cost to chain"
    return "", ""


def main():
    bench = {r["mnemonic"]: r for r in
             csv.DictReader(open(BENCH), delimiter="\t")}
    corr = {r["mnemonic"]: r for r in
            csv.DictReader(open(CORR), delimiter="\t")}
    rows = []
    for m in sorted(set(bench) | set(corr)):
        b = bench.get(m, {})
        c = corr.get(m, {})
        fam, why = classify(m)
        rows.append({
            "mnemonic": m,
            "bench": b.get("status", "NO-ROW"),
            "correctness": c.get("status", "NO-ROW"),
            "family": fam,
            "reason": why if b.get("status", "NO-ROW") != "OK" else "",
        })
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else OUT
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["mnemonic", "bench", "correctness",
                                          "family", "reason"], delimiter="\t")
        w.writeheader()
        w.writerows(rows)

    ok = sum(1 for r in rows if r["bench"] == "OK")
    skip = sum(1 for r in rows if r["bench"] == "SKIP")
    # the interesting split: benchable-in-principle vs carrier-limited
    tmpl = [r for r in rows if r["bench"] == "SKIP" and r["correctness"] == "PASS"]
    car = [r for r in rows if r["bench"] == "SKIP" and r["correctness"].startswith("SKIP")]
    print("rows=%d  bench OK=%d  bench SKIP=%d" % (len(rows), ok, skip))
    print("  SKIP but correctness PASS (template gap) : %d" % len(tmpl))
    print("  SKIP and correctness SKIP (carrier limit): %d" % len(car))
    print("  -> %s" % out)
    print()
    agg = collections.Counter((r["family"], r["reason"]) for r in tmpl)
    print("%-30s %-42s %5s" % ("family (template gap)", "why", "rows"))
    for (fam, why), n in sorted(agg.items(), key=lambda kv: -kv[1]):
        print("%-30s %-42s %5d" % (fam, why[:42], n))


if __name__ == "__main__":
    main()
