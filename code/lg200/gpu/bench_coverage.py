#!/usr/bin/env python3
"""CS bench coverage manifest: what is measured, what is not, and why.

Joins three sources that already exist and are regenerated by the normal
workflow:

  build/cs_bench_results.tsv        run_bench.py (per-mnemonic OK/SKIP)
  build/gpu_cs_generic_results.tsv  run_gpu.py --pipe cs (correctness status)

and adds the family + reason for every row the bench cannot measure.  The point
is that "497 of 768" is auditable rather than a claim: a row that PASSES
correctness but has no bench row is a per-family template gap, while a row that
is SKIP-ENVELOPE on correctness too is a carrier limitation.

    python3 bench_coverage.py [--out build/cs_bench_coverage.tsv]
"""
import csv
import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BENCH = ROOT / "build" / "cs_bench_results.tsv"
CORR = ROOT / "build" / "gpu_cs_generic_results.tsv"
OUT = ROOT / "build" / "cs_bench_coverage.tsv"

# The ISA source, so every row carries its own provenance rather than leaving the
# reader to infer it from the document header.
ISA = ROOT.parent.parent / "lg200-instructions.tsv"

# family -> (prefixes, why the bench has no template for it)
FAMILIES = [
    (("atomic_sm_cmpswap",),
     "shared memory (LDS) compare-swap",
     "the compare-swap operand pair is not verified on the compute pipe"),
    (("atomic_v_flat", "load_v_flat", "store_v_flat", "load_s_flat",
      "store_s_flat"), "flat memory", "needs a flat address operand"),
    (("atomic_v_buff", "load_v_buff", "store_v_buff", "load_s_buff",
      "store_s_buff"), "buffer memory", "needs a hydrated buffer descriptor"),
    (("atomic_v_tex", "load_v_tex", "store_v_tex"), "texture memory",
     "needs a texture descriptor"),
    (("samp", "gather"), "sampler / gather",
     "needs a texture + sampler descriptor"),
    (("sio",), "SIO", "outside the codec's variants"),
    (("v_movindex",), "refused by name", "its register window wedged CPIPE"),
]
CONTROL = ("nop", "exit", "check", "barrier", "trap", "rfe", "b", "jirl",
           "jpop", "jpush", "cb", "czb", "flag", "getpc", "getreg", "getlod",
           "getresinfo", "v_emit2", "v_emit3", "prefix_sw", "prefix_tp4",
           "prefix_tp8")


def classify(m):
    for prefixes, fam, why in FAMILIES:
        if m.startswith(prefixes):
            return fam, why
    if m in CONTROL:
        return "control / flow / system", "no cost to chain"
    return "", ""


def main():
    bench = {r["mnemonic"]: r for r in
             csv.DictReader(open(BENCH), delimiter="\t")}
    corr = {r["mnemonic"]: r for r in
            csv.DictReader(open(CORR), delimiter="\t")}
    desc = {}
    with open(ISA) as f:
        for r in csv.DictReader(f, delimiter=chr(9)):
            desc[r["mnemonic"]] = r.get("description") or ""
    rows = []
    for m in sorted(set(bench) | set(corr)):
        b = bench.get(m, {})
        c = corr.get(m, {})
        fam, why = classify(m)
        rows.append({
            "mnemonic": m,
            "bench": b.get("status", "NO-ROW"),
            "correctness": c.get("status", "NO-ROW"),
            "family": fam,
            "reason": why if b.get("status", "NO-ROW") != "OK" else "",
            # Carried through because a status alone does not say whether the row was
            # OBSERVED.  376 of the 377 HANG/FAULT rows share one detail - the device
            # node was gone - so they never ran, and reading them as faults of those
            # instructions is wrong.
            "detail": (c.get("detail") or "").strip(),
            # Per-row provenance: which u-l-i-g page this row claims against, and
            # whether that page leaves any part of the row UNRESOLVED.  A timing here
            # would rest on a page that says so, which the CSV should show.
            "isa_source": "code/lg200/%s.cpp" % m,
            "unresolved": "yes" if "UNRESOLVED" in desc.get(m, "") else "",
        })
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else OUT
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["mnemonic", "bench", "correctness",
                                          "family", "reason", "detail",
                                          "isa_source", "unresolved"],
                           delimiter="\t")
        w.writeheader()
        w.writerows(rows)

    # The provenance columns join by mnemonic, and a miss would leave them empty
    # and look like a row with nothing to say.  A row with no u-l-i-g page is a
    # different problem and should be said out loud.
    orphan = [r["mnemonic"] for r in rows if not r["isa_source"]
              or r["mnemonic"] not in desc]
    if orphan:
        print("no u-l-i-g page for %d rows, e.g. %s"
              % (len(orphan), ", ".join(orphan[:5])), file=sys.stderr)
        return 1

    ok = sum(1 for r in rows if r["bench"] == "OK")
    skip = sum(1 for r in rows if r["bench"] == "SKIP")
    # The interesting split is benchable-in-principle vs carrier-limited, and the
    # CARRIER'S OWN refusal is the stable side of it: a row the correctness
    # carrier refuses (SKIP-ENVELOPE) cannot be benchmarked whatever the rest of
    # the matrix says.  Classifying by PASS instead makes the split depend on the
    # matrix being a clean run: the matrix on disk is the run that WEDGED, so
    # hundreds of rows are neither PASS nor SKIP and silently fell out of both
    # buckets, undercounting the template gaps.
    car = [r for r in rows if r["bench"] == "SKIP" and r["correctness"].startswith("SKIP")]
    tmpl = [r for r in rows if r["bench"] == "SKIP"
            and not r["correctness"].startswith("SKIP")]
    print("rows=%d  bench OK=%d  bench SKIP=%d" % (len(rows), ok, skip))
    print("  SKIP and correctness SKIP (carrier limit): %d" % len(car))
    print("  SKIP for any other reason (template gap) : %d" % len(tmpl))
    health = collections.Counter(r["correctness"] for r in rows)
    dirty = {k: v for k, v in health.items() if k not in ("PASS", "SKIP-ENVELOPE")}
    print("  matrix health: %s" % ", ".join("%s=%d" % kv for kv in health.most_common()))
    if dirty:
        print("  WARNING: the matrix is not a clean run (%s) - every number above"
              % ", ".join("%s=%d" % kv for kv in sorted(dirty.items())))
        print("           that mentions correctness beyond the carrier's own SKIP"
              " is unreliable.")
        # Say WHICH rows are unobserved rather than calling all of them unreliable.
        # A dirty status with the device node gone means the row never ran.
        gone = [r for r in rows if "cannot open /dev/dri" in r["detail"]]
        faulted = [r for r in rows
                   if r["correctness"] in dirty and "cannot open /dev/dri" not in r["detail"]]
        if gone:
            print("           %d of those share one detail - the device node was gone,"
                  % len(gone))
            print("           so they NEVER RAN and are not observations of those rows.")
            print("           first unrun row: %s" % gone[0]["mnemonic"])
        if faulted:
            print("           %d other row(s) carry a submission detail: %s"
                  % (len(faulted), ", ".join(r["mnemonic"] for r in faulted[:4])))
    print("  -> %s" % out)
    print()
    agg = collections.Counter((r["family"], r["reason"]) for r in tmpl)
    print("%-30s %-42s %5s" % ("family (template gap)", "why", "rows"))
    for (fam, why), n in sorted(agg.items(), key=lambda kv: -kv[1]):
        print("%-30s %-42s %5d" % (fam, why[:42], n))


if __name__ == "__main__":
    main()
