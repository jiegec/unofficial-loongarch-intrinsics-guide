/*
 * Verify the vendored MCS builder against the vendor's own bytes.
 *
 * `expected` is the output of the loonggpu tree's analysis/lacm/mcs_ref.c, which
 * calls the vendor runtime's emitters by address for one real add.cl dispatch
 * and prints the resulting stream.  If our builder reproduces it byte for byte,
 * the encoding is confirmed against the vendor rather than against a reading of
 * it.
 *
 * The inputs are the live-captured values from that dispatch.  Two of them are
 * not directly visible in the stream and are recovered from it:
 *   - rsrc0 = 0x42 requires granulated(sgprs, vgprs) = 0x42, i.e. sgprs in 1..8
 *     and vgprs in 5..8; 8 and 8 are used.
 *   - rsrc1' = 0x083c2076 is reproduced by shape_rsrc1(LOONGVK_KD_RSRC1,
 *     {1,1,1}, LOONGVK_KD_FLOAT_MODE_DEFAULT); checked in the assert below.
 */
#include "loongvk_mcs.h"
#include "mcs_kd.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

static const uint8_t expected[192] = {
    0x89, 0x01, 0x30, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00,
    0x00, 0x00, 0x02, 0x00, 0x89, 0x08, 0x40, 0x00, 0xa8, 0x99, 0x00, 0xe8,
    0x13, 0x00, 0x00, 0x00, 0x42, 0x00, 0x00, 0x00, 0x76, 0x20, 0x3c, 0x08,
    0x89, 0x10, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80,
    0x00, 0x00, 0x00, 0x00, 0xac, 0x4f, 0xca, 0x00, 0x89, 0x14, 0x20, 0x00,
    0x20, 0x01, 0x20, 0xe8, 0x13, 0x00, 0x00, 0x00, 0x89, 0x16, 0x20, 0x00,
    0x80, 0x00, 0x20, 0xe8, 0x13, 0x00, 0x00, 0x00, 0x89, 0x18, 0x20, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x89, 0x1a, 0x10, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x87, 0x07, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x8d, 0x00, 0x00, 0x00,
    0x8b, 0x0f, 0x00, 0x00, 0x8a, 0x00, 0x00, 0x00, 0x80, 0xf7, 0xbf, 0x00,
    0x04, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
};

int
main(void)
{
   const struct loongvk_mcs_dispatch d = {
      .kd_flags = 0x0fac,
      .kernel_object = 0x00000013e8200120ull,
      .entry = 0x00000013e80099a8ull,
      .kernarg_address = 0x00000013e8200080ull,
      .completion_signal = 0x0000000400bff780ull,
      .num_sgprs = 8,
      .num_vgprs = 8,
      .shared_segment_size = 0,
      .group_size = { 1, 1, 1 },
      .grid_size = { 1, 1, 1 },
      /* The vendor hardcodes this four-dword private-buffer descriptor for a
       * dispatch with no scratch region; the low half of the last word carries
       * the .kd flag bits.  It is an input, not something the builder derives,
       * which is why leaving it zero produced a four-byte difference. */
      .scratch_resource_descriptor = { 0u, 0x80000000u, 0u, 0x00ca4facu },
      .group_aperture_hi = 0x00010000u,
      .private_aperture_hi = 0x00020000u,
      .float_mode = LOONGVK_KD_FLOAT_MODE_DEFAULT,
   };

   uint8_t out[LOONGVK_MCS_MAX_LEN];
   size_t len = 0;
   if (!loongvk_mcs_build_dispatch(out, sizeof out, &d, &len)) {
      fprintf(stderr, "build_dispatch failed\n");
      return 2;
   }
   if (len != sizeof expected) {
      fprintf(stderr, "length %zu, vendor %zu\n", len, sizeof expected);
      return 2;
   }
   unsigned diffs = 0;
   for (size_t i = 0; i < len; ++i) {
      if (out[i] != expected[i]) {
         if (diffs < 12)
            fprintf(stderr, "  [%3zu] ours 0x%02x vendor 0x%02x\n", i, out[i],
                    expected[i]);
         ++diffs;
      }
   }
   printf("len=%zu bytes, %u differing\n", len, diffs);
   return diffs ? 1 : 0;
}
